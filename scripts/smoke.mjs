import { _electron as electron } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir,mkdtemp,readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join,resolve } from 'node:path';

const data=await mkdtemp(join(tmpdir(),'bolha-smoke-'));
const packaged=process.env.BOLHA_SMOKE_EXE;
const args=packaged?[]:['.'];
if(process.platform==='linux')args.unshift('--no-sandbox');
const app=await electron.launch({executablePath:packaged,args,env:{...process.env,BOLHA_TEST:'1',BOLHA_TEST_USER_DATA:data},timeout:45000});
try {
  const page=await app.firstWindow();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.waitForSelector('[data-app-ready]',{timeout:30000});
  await page.waitForSelector('[data-testid=bolha]',{timeout:30000});
  const boot=await page.evaluate(()=>window.bolha.bootstrap());
  assert.equal(boot.preferences.roaming,true);assert.equal(boot.brain.neurons,470);
  assert.equal(boot.preferences.adaptiveBehavior,true);assert.equal(boot.preferences.learnRoutine,true);
  await page.evaluate(()=>window.bolha.brainEvent({type:'caress'}));
  await page.getByText('Tá, esse carinho eu aceito. ♡',{exact:true}).waitFor();
  assert.equal((await page.evaluate(()=>window.bolha.bootstrap())).brain.ready,true);
  await page.evaluate(()=>window.bolha.brainEvent({type:'panel',value:true}));
  await page.evaluate(()=>window.bolha.brainEvent({type:'monitor',value:true}));
  await page.evaluate(()=>window.dispatchEvent(new MouseEvent('contextmenu')));
  await page.evaluate(()=>document.querySelector('[data-testid=bolha]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true})));
  await page.getByRole('heading',{name:'Bolha',exact:true}).waitFor();
  await page.getByRole('button',{name:'Vida',exact:true}).click();
  assert.equal(await page.getByRole('slider').count(),3);
  await page.getByRole('button',{name:'Acompanhar o cérebro'}).click();
  await page.getByRole('heading',{name:'Por dentro da Bolha'}).waitFor();
  await page.waitForFunction(()=>document.querySelector('canvas')?.width===420);
  await page.getByRole('heading',{name:'Objetivo agora'}).waitFor();
  await mkdir('validation',{recursive:true});
  await page.screenshot({path:'validation/neural-smoke.png'});
  await page.getByRole('button',{name:'Fechar painel'}).click();
  await page.evaluate(()=>document.querySelector('[data-testid=bolha]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true})));
  await page.getByRole('heading',{name:'Bolha',exact:true}).waitFor();
  await page.screenshot({path:'validation/settings-smoke.png'});
  await page.getByRole('button',{name:'Fechar painel'}).click();
  await page.evaluate(()=>{window.bolha.savePreferences({roaming:false});window.bolha.brainEvent({type:'rest'});});
  await page.waitForSelector('.companion[data-pose=lying]',{timeout:15000});
  await page.waitForFunction(()=>Math.abs(Math.atan2(new DOMMatrix(getComputedStyle(document.querySelector('.bolha-avatar-face')).transform).b,new DOMMatrix(getComputedStyle(document.querySelector('.bolha-avatar-face')).transform).a)*180/Math.PI+72)<2);
  const core=await page.locator('.bolha-avatar-core').boundingBox();
  assert.ok(Math.abs(core.width-core.height)<2,'Deitar move o rosto e preserva a esfera redonda.');
  assert.equal(await page.locator('.bolha-ear').count(),2);
  const eyes=await page.locator('.bolha-eye').evaluateAll(eyes=>eyes.map(eye=>[eye.getAttribute('rx'),eye.getAttribute('ry')]));
  assert.ok(eyes[0].every((value,index)=>Math.abs(Number(value)-Number(eyes[1][index]))<.05),'Os olhos devem manter tamanho e piscadas uniformes.');
  await page.screenshot({path:'validation/lying-smoke.png'});
  const box=await page.locator('.companion').boundingBox();
  const before=(await page.evaluate(()=>window.bolha.bootstrap())).brain;
  await page.mouse.move(box.x+box.width*.65,box.y+box.height*.5);
  await page.mouse.down();
  await page.waitForFunction(async()=>((await window.bolha.bootstrap()).brain).held);
  const grabbed=(await page.evaluate(()=>window.bolha.bootstrap())).brain;
  assert.ok(Math.abs(grabbed.x-before.x)<3,'Pegar pela borda não deve puxar o centro para o cursor.');
  const viewport=await page.evaluate(()=>({width:innerWidth,height:innerHeight}));
  const deltaX=box.x+box.width+120<viewport.width?100:-100;
  await page.mouse.move(box.x+box.width*.65+deltaX,box.y+box.height*.5-100,{steps:10});
  const dragged=await page.locator('.companion').boundingBox();
  assert.ok(Math.abs(dragged.x-box.x-deltaX)<8,'O desenho deve acompanhar o arrasto sem esperar o próximo estado.');
  await page.mouse.up();
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.bolha-face-float').evaluate(el=>getComputedStyle(el).animationName),'none');
  await page.emulateMedia({reducedMotion:'no-preference'});
  assert.equal(await page.locator('.desktop').evaluate(el=>/drippy/i.test(el.textContent)),false);
  assert.deepEqual(errors,[]);
  const health=JSON.parse(await readFile(join(data,'health.json'),'utf8'));
  assert.equal(health.neurons,470);
  console.log(JSON.stringify({platform:process.platform,renderer:true,brain:470,settings:true,neuralPanel:true,faceLiesIndependently:true,grabOffset:true,directDrag:true,reducedMotion:true,brand:'Bolha',screenshot:'validation/lying-smoke.png',errors}));
} finally { await app.close(); }
